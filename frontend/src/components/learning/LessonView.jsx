import React from 'react';
import { Card } from '../common/Card';
import { Button } from '../common/Button';
import { DifficultyBadge } from '../common/Badge';
import { BookOpenIcon, CheckCircleIcon, ArrowRightIcon, SparklesIcon } from '../common/Icons';

export function LessonView({ cycle, onProceedToQuiz }) {
  if (!cycle) {
    return (
      <Card padding="3rem" style={{ textAlign: 'center', color: 'var(--text-secondary)' }}>
        No lesson content available for this cycle.
      </Card>
    );
  }

  const { cycle_number, difficulty_level, explanation, notes } = cycle;

  // Split explanation into clean paragraphs for pleasant readability
  const paragraphs = (explanation || '')
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter(Boolean);

  return (
    <div className="lesson-view">
      {/* Lesson Explanation Card */}
      <Card padding="2.25rem" style={{ marginBottom: '2rem' }}>
        <div
          style={{
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
            marginBottom: '1.25rem',
            borderBottom: '1px solid var(--border-subtle)',
            paddingBottom: '1rem',
          }}
        >
          <div style={{ display: 'flex', alignItems: 'center', gap: '0.65rem' }}>
            <div
              style={{
                width: '36px',
                height: '36px',
                borderRadius: 'var(--radius-md)',
                backgroundColor: 'var(--bg-soft)',
                color: 'var(--color-primary)',
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
              }}
            >
              <BookOpenIcon size={20} />
            </div>
            <div>
              <h2
                style={{
                  fontSize: '1.35rem',
                  fontWeight: '700',
                  color: 'var(--text-main)',
                  letterSpacing: '-0.01em',
                }}
              >
                Cycle {cycle_number} Pedagogical Explanation
              </h2>
              <div style={{ fontSize: '0.8rem', color: 'var(--text-muted)' }}>
                Targeted conceptual lesson generated by Gemini AI
              </div>
            </div>
          </div>

          <DifficultyBadge difficulty={difficulty_level} size="sm" />
        </div>

        {/* Formatted Paragraphs */}
        <div
          style={{
            fontSize: '1rem',
            lineHeight: 1.7,
            color: 'var(--text-main)',
          }}
        >
          {paragraphs.length > 0 ? (
            paragraphs.map((para, idx) => (
              <p key={idx} style={{ marginBottom: '1.25rem' }}>
                {para}
              </p>
            ))
          ) : (
            <p>{explanation}</p>
          )}
        </div>
      </Card>

      {/* Key Revision Notes Card */}
      {notes && notes.length > 0 && (
        <Card padding="2rem" style={{ marginBottom: '2.5rem', backgroundColor: 'var(--bg-card)' }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', marginBottom: '1rem' }}>
            <SparklesIcon size={18} className="text-olive" />
            <h3
              style={{
                fontSize: '1.15rem',
                fontWeight: '700',
                color: 'var(--text-main)',
                letterSpacing: '-0.01em',
              }}
            >
              Key Takeaway Revision Notes ({notes.length})
            </h3>
          </div>

          <div
            style={{
              display: 'grid',
              gridTemplateColumns: 'repeat(auto-fit, minmax(280px, 1fr))',
              gap: '1rem',
            }}
          >
            {notes.map((note, idx) => (
              <div
                key={idx}
                style={{
                  padding: '1.15rem 1.25rem',
                  borderRadius: 'var(--radius-md)',
                  backgroundColor: 'var(--bg-main)',
                  border: '1px solid var(--border-subtle)',
                  display: 'flex',
                  alignItems: 'flex-start',
                  gap: '0.75rem',
                }}
              >
                <div
                  style={{
                    width: '24px',
                    height: '24px',
                    borderRadius: '50%',
                    backgroundColor: 'var(--color-primary)',
                    color: '#FFFDFA',
                    fontSize: '0.75rem',
                    fontWeight: '700',
                    display: 'flex',
                    alignItems: 'center',
                    justifyContent: 'center',
                    flexShrink: 0,
                    marginTop: '2px',
                  }}
                >
                  {idx + 1}
                </div>
                <div style={{ fontSize: '0.92rem', color: 'var(--text-main)', lineHeight: 1.5 }}>
                  {note}
                </div>
              </div>
            ))}
          </div>
        </Card>
      )}

      {/* Transition Banner to Quiz */}
      <Card
        padding="2rem"
        style={{
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          backgroundColor: 'var(--bg-soft)',
          border: '1.5px solid var(--border-subtle)',
          flexWrap: 'wrap',
          gap: '1.25rem',
        }}
      >
        <div>
          <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', color: 'var(--color-primary)', fontWeight: '700', fontSize: '0.8rem', textTransform: 'uppercase', marginBottom: '0.2rem' }}>
            <CheckCircleIcon size={16} />
            <span>Ready for Assessment?</span>
          </div>
          <h4 style={{ fontSize: '1.2rem', fontWeight: '700', color: 'var(--text-main)', marginBottom: '0.25rem' }}>
            Test your understanding with 12 diagnostic MCQs
          </h4>
          <p style={{ fontSize: '0.88rem', color: 'var(--text-secondary)' }}>
            Each question has 4 distinct options and is graded securely on the server.
          </p>
        </div>

        <Button
          variant="primary"
          size="lg"
          onClick={onProceedToQuiz}
          rightIcon={<ArrowRightIcon size={18} />}
        >
          Proceed to Practice Quiz
        </Button>
      </Card>
    </div>
  );
}

